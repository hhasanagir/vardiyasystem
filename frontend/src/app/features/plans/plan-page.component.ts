  private isPolyclinicClosed(device: DeviceInfo, day: DayColumn): boolean {
    if (device.mode !== 'polyclinic') return false;
    if (day.isHoliday) return true;
    if (this.selectedUnit() === 'nukleer') return day.dayNum === 0;
    return day.isWeekend;
  }

  private isMonthlyShiftOff(device: DeviceInfo, day: DayColumn): boolean {
    return this.isPolyclinicClosed(device, day);
  }

  async applyMonthlyAssignment(): Promise<void> {
    const vs = this.viewState();
    const deviceId = this.monthlyDeviceId();
    const shiftType = this.monthlyShiftType();
    const personnelId = this.monthlyPersonnelId();
    if (vs.status !== 'success' || !vs.schedule.id || !deviceId || !shiftType || !personnelId) {
      this.monthlyResult.set('Cihaz, vardiya ve personel seçmelisiniz.');
      return;
    }
    const scheduleId = vs.schedule.id;
    const device = this.devices().find((d) => d.id === deviceId);
    const slot = device?.shifts.find((s) => s.type === shiftType);
    const normalized = this.normalizeShift(shiftType);
    const isNight = normalized === 'night';
    const startTime = slot?.startTime || (isNight ? '20:00' : '08:00');
    const endTime = slot?.endTime || (isNight ? '08:00' : '20:00');
    const year = vs.schedule.year;
    const month = vs.schedule.month;
    const daysInMonth = new Date(year, month, 0).getDate();

    this.monthlyBusy.set(true);
    this.monthlyResult.set('');
    let assigned = 0;
    let skipped = 0;
    let failed = 0;
    try {
      for (let d = 1; d <= daysInMonth; d++) {
        const dateStr = `${year}-${String(month).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
        const day: DayColumn = this.days()[d - 1];
        if (device && this.isMonthlyShiftOff(device, day)) {
          skipped++;
          continue;
        }
        try {
          await firstValueFrom(
            this.scheduleApi.assignPersonnel(
              scheduleId,
              {
                deviceId,
                date: dateStr,
                shiftType: normalized,
                personnelId,
                personnelType: slot?.personnelType || undefined,
                startTime,
                endTime,
              },
              'Aylık atama',
            ),
          );
          assigned++;
        } catch {
          failed++;
        }
      }
      this.monthlyResult.set(
        `Tamamlandı — Atandı: ${assigned}, Kapalı gün atlandı: ${skipped}, Başarısız: ${failed}`,
      );
      this.refresh();
    } finally {
      this.monthlyBusy.set(false);
    }
  }

