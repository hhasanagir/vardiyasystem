function computeFairnessScore(assignments: ShiftAssignment[]): number {
  if (assignments.length === 0) return 100;
  const keyOf = (a: ShiftAssignment) => a.personnelId || a.personnelName || 'Bilinmeyen';
  const totals = new Map<string, number>();
  const nights = new Map<string, number>();
  for (const a of assignments) {
    const k = keyOf(a);
    totals.set(k, (totals.get(k) || 0) + 1);
    const st = (a.shiftType || '').toLowerCase();
    if (
      st === 'gece' ||
      st === 'night' ||
      st === 'aksam' ||
      st === 'akşam' ||
      st === 'evening' ||
      st.includes('gece')
    ) {
      nights.set(k, (nights.get(k) || 0) + 1);
    }
  }
  const distScore = (m: Map<string, number>): number => {
    const counts = [...m.values()];
    if (counts.length === 0) return 100;
    const mean = counts.reduce((s, c) => s + c, 0) / counts.length;
    if (mean <= 0) return 100;
    const avgDev = counts.reduce((s, c) => s + Math.abs(c - mean), 0) / counts.length / mean;
    return Math.max(0, Math.round(100 - avgDev * 100));
  };
  const totalScore = distScore(totals);
  const nightScore = nights.size > 0 ? distScore(nights) : totalScore;
  return Math.round(totalScore * 0.7 + nightScore * 0.3);
}

function computeFairnessBreakdown(assignments: ShiftAssignment[]): string[] {
  const keyOf = (a: ShiftAssignment) => a.personnelId || a.personnelName || 'Bilinmeyen';
  const totals = new Map<string, number>();
  const nights = new Map<string, number>();
  for (const a of assignments) {
    const k = keyOf(a);
    totals.set(k, (totals.get(k) || 0) + 1);
    const st = (a.shiftType || '').toLowerCase();
    if (
      st === 'gece' ||
      st === 'night' ||
      st === 'aksam' ||
      st === 'akşam' ||
      st === 'evening' ||
      st.includes('gece')
    ) {
      nights.set(k, (nights.get(k) || 0) + 1);
    }
  }
  const nightOf = (k: string) => nights.get(k) || 0;
  return [...totals.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(
      ([name, total]) =>
        `${name}: ${total} vardiya${nightOf(name) ? ` (${nightOf(name)} gece)` : ''}`,
    );
}

