  private loadMonthlyPersonnel(unitType: string): void {
    this.monthlyPersonnel.set([]);
    this.api
      .get<
        {
          id: string;
          name: string;
          skills?: string[];
          unit?: { id: string; code?: string; type?: string; name?: string };
        }[]
      >('/personnel', { params: { isActive: 'true', unitId: unitType } })
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (list) => {
          const ut = unitType.toLowerCase();
          const filtered = (list || []).filter((p) => {
            if (!ut) return true;
            const u = p.unit;
            if (!u) return false;
            return u.type === ut || (u.code && u.code.toLowerCase() === ut) || u.id === unitType;
          });
          this.monthlyPersonnel.set(filtered);
        },
        error: () => this.monthlyPersonnel.set([]),
      });
  }

