  // Assignment validation warnings
  validationWarnings = computed(() => {
    const warnings: Array<{
      type: string;
      message: string;
      severity: 'warning' | 'error';
      date?: string;
      deviceId?: string;
      shiftType?: string;
      alertKey: string;
    }> = [];
    const vs = this.viewState();
    if (vs.status !== 'success') return warnings;
    const assignments = vs.schedule.assignments;

    // Double assignment same day
    const personDayMap = new Map<string, string[]>();
    for (const a of assignments) {
      if (!a.personnelId) continue;
      const key = `${a.personnelId}|${a.date}`;
      if (!personDayMap.has(key)) personDayMap.set(key, []);
      personDayMap.get(key)!.push(a.shiftType);
    }
    for (const [key, shifts] of personDayMap) {
      if (shifts.length > 1) {
        const [pid, date] = key.split('|');
        const name = assignments.find((a) => a.personnelId === pid)?.personnelName || pid;
        warnings.push({
          type: 'double',
          message: `${name}: ${date} tarihinde ${shifts.length} vardiya`,
          severity: 'error',
          date,
          alertKey: `double|${key}`,
        });
      }
    }

    // Night-to-day rest violation
    const nightPersonnel = new Map<string, Set<string>>();
    for (const a of assignments) {
      const s = a.shiftType.toLowerCase();
      if (s.includes('night') || s.includes('gece') || a.startTime >= '20') {
        if (!nightPersonnel.has(a.personnelId)) nightPersonnel.set(a.personnelId, new Set());
        nightPersonnel.get(a.personnelId)!.add(a.date);
      }
    }
    for (const a of assignments) {
      if (!a.personnelId) continue;
      const s = a.shiftType.toLowerCase();
      if (s.includes('day') || s.includes('gunduz') || s.includes('sabah') || a.startTime < '12') {
        const prevDate = new Date(a.date);
        prevDate.setDate(prevDate.getDate() - 1);
        const prevStr = prevDate.toISOString().split('T')[0];
        const nights = nightPersonnel.get(a.personnelId);
        if (nights && nights.has(prevStr)) {
          const name = a.personnelName || a.personnelId;
          warnings.push({
            type: 'rest',
            message: `${name}: Gece ertesinde gündüz (${a.date})`,
            severity: 'error',
            date: a.date,
            deviceId: a.deviceId,
            shiftType: a.shiftType,
            alertKey: `rest|${a.id}`,
          });
        }
      }
    }

    // Weekly overload (>5 shifts in 7-day window)
    const weekMap = new Map<string, Map<string, number>>();
    for (const a of assignments) {
      if (!a.personnelId) continue;
      const d = new Date(a.date);
      const ws = new Date(d);
      ws.setDate(d.getDate() - d.getDay());
      const wk = ws.toISOString().split('T')[0];
      if (!weekMap.has(a.personnelId)) weekMap.set(a.personnelId, new Map());
      const pw = weekMap.get(a.personnelId)!;
      pw.set(wk, (pw.get(wk) || 0) + 1);
    }
    for (const [pid, wm] of weekMap) {
      for (const [wk, cnt] of wm) {
        if (cnt > 5) {
          const name = assignments.find((a) => a.personnelId === pid)?.personnelName || pid;
          warnings.push({
            type: 'overload',
            message: `${name}: ${wk} haftasında ${cnt} vardiya`,
            severity: 'warning',
            alertKey: `overload|${pid}|${wk}`,
          });
        }
      }
    }

    return warnings;
  });

