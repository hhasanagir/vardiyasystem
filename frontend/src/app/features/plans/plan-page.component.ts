  kpiBreakdown = computed(() => {
    const map = new Map<string, string[]>();
    const vs = this.viewState();
    if (vs.status !== 'success') return map;
    const { assignments, devices, deviceShiftConfig } = vs.schedule;
    const daysInMonth = this.days();

    const slots: Array<{ deviceId: string; type: string; mode: string; startTime: string }> = [];
    for (const d of devices) {
      const cfg = deviceShiftConfig?.find((c) => c.deviceId === d.id);
      const shifts = cfg?.shifts || [];
      const seen = new Set<string>();
      for (const s of shifts) {
        const key = `${s.type}|${s.personnelType || 'default'}`;
        if (seen.has(key)) continue;
        seen.add(key);
        slots.push({ deviceId: d.id, type: s.type, mode: d.mode, startTime: s.startTime });
      }
      if (shifts.length === 0) {
        slots.push({ deviceId: d.id, type: 'day', mode: d.mode, startTime: '08:00' });
        if (d.mode === 'vardiya')
          slots.push({ deviceId: d.id, type: 'night', mode: d.mode, startTime: '20:00' });
      }
    }

    const totalSlots = slots.length * daysInMonth.length;
    const shiftLabelMap: Record<string, string> = {
      day: 'Gündüz',
      night: 'Gece',
      evening: 'İkindi',
      morning: 'Sabah',
    };
    const totalByShift = new Map<string, number>();
    const assignedByShift = new Map<string, number>();
    for (const s of slots) {
      const key = this.normalizeShift(s.type);
      totalByShift.set(key, (totalByShift.get(key) || 0) + daysInMonth.length);
    }
    for (const a of assignments) {
      const key = this.normalizeShift(a.shiftType);
      assignedByShift.set(key, (assignedByShift.get(key) || 0) + 1);
    }
    const shiftBreakdown = [...totalByShift.keys()].map((k) => {
      const assigned = assignedByShift.get(k) || 0;
      const total = totalByShift.get(k) || 0;
      return `${shiftLabelMap[k] || k}: ${assigned}/${total}`;
    });

    map.set('assigned', shiftBreakdown);
    map.set('unassigned', shiftBreakdown);
    map.set('emptyAlarm', shiftBreakdown);
    map.set('totalSlots', [`Toplam slot: ${totalSlots}`]);
    map.set('occupancyPct', [`Dolu: ${assignments.length} / ${totalSlots}`]);
    map.set('usageRate', [`Dolu: ${assignments.length} / ${totalSlots}`]);
    map.set('fairness', computeFairnessBreakdown(assignments));

    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const three = new Date(today.getTime() + 3 * 86400000);
    let critical = 0;
    for (const day of daysInMonth) {
      const dt = new Date(day.date);
      dt.setHours(0, 0, 0, 0);
      if (dt < today || dt > three) continue;
      for (const s of slots) {
        const device = this.devices().find((d) => d.id === s.deviceId);
        if (device && this.isPolyclinicClosed(device, day)) continue;
        const filled = assignments.some(
          (a) =>
            a.deviceId === s.deviceId &&
            a.date === day.dateStr &&
            this.shiftTypeMatches(a.shiftType, s.type),
        );
        if (!filled) critical++;
      }
    }
    map.set('criticalGaps', [`Önümüzdeki 3 gün boş slot: ${critical}`]);

    const holidayNames = [
      ...new Set(
        daysInMonth.filter((d) => d.isHoliday && d.holidayName).map((d) => d.holidayName as string),
      ),
    ];
    map.set('holidayCount', holidayNames.length ? holidayNames : ['Bu ayda tatil yok']);
    return map;
  });

