function mapHttpError(err: unknown): { message: string; code: number; endpoint?: string } {
  const map: Record<number, string> = {
    500: 'Sistemsel hata oluştu. Plan verileri alınamadı.',
    404: 'Bu birim için plan bulunamadı.',
    403: 'Bu işlem için yetkiniz bulunmuyor.',
    401: 'Oturum süreniz doldu. Lütfen tekrar giriş yapın.',
    400: 'Geçersiz istek. Lütfen sayfayı yenileyip tekrar deneyin.',
    0: 'Sunucuya ulaşılamıyor. Lütfen bağlantınızı kontrol edin.',
  };
  const e = err as { statusCode?: number; status?: number; message?: string; path?: string };
  const code = e?.statusCode ?? e?.status ?? 0;
  return {
    code,
    message: map[code] || e?.message || 'Beklenmeyen bir hata oluştu.',
    endpoint: e?.path,
  };
}

