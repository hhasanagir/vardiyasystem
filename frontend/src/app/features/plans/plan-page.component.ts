  // ---- Alert resolve / dismiss ----

  private alertKeyOf(a: ScheduleAlert): string {
    return `${a.type}|${a.deviceId || ''}|${a.date || ''}|${a.message}`;
  }

  activeAlerts = computed(() =>
    this.alerts().filter((a) => !this.resolvedAlerts().has(this.alertKeyOf(a))),
  );

  onResolveAlert(e: {
    alertKey?: string;
    deviceId?: string;
    date?: string;
    shiftType?: string;
  }): void {
    if (e.alertKey) {
      this.resolvedAlerts.update((s) => new Set([...s, e.alertKey!]));
      return;
    }
    if (e.deviceId && e.date) {
      const shiftType = e.shiftType || this.firstShiftForDevice(e.deviceId);
      this.onAddAssignment({
        deviceId: e.deviceId,
        date: e.date,
        shiftType,
        personnelType: undefined,
      });
    }
  }

  private firstShiftForDevice(deviceId: string): string {
    const device = this.devices().find((d) => d.id === deviceId);
    return device?.shifts[0]?.type || 'day';
  }
  private normalizeShift(shiftType: string): string {
    const map: Record<string, string> = {
      gunduz: 'day',
      gece: 'night',
      sabah: 'morning',
      ikindi: 'evening',
      aksam: 'evening',
    };
    return map[shiftType.toLowerCase()] || shiftType;
  }

  private defaultSlotTimes(shiftType: string): { startTime: string; endTime: string } {
    const n = this.normalizeShift(shiftType);
    if (n === 'night') return { startTime: '20:00', endTime: '08:00' };
    if (n === 'evening') return { startTime: '15:00', endTime: '23:00' };
    if (n === 'morning') return { startTime: '07:30', endTime: '15:30' };
    return { startTime: '08:00', endTime: '16:00' };
  }

