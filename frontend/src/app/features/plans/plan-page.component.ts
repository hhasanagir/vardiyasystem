  private validateDropTarget(
    src: DragAssignment,
    deviceId: string,
    date: string,
    shiftType: string,
    targetPersonnelType?: string | null,
  ): { ok: boolean; message?: string } {
    const personnelId = src.personnelId;
    const personnelName = src.personnelName || 'Bu personel';

    if (!personnelId) return { ok: false, message: 'Taşınan personel bulunamadı.' };

    const sameShiftConflict = this.assignmentCache().find(
      (a) =>
        a.personnelId === personnelId && a.date === date && shiftsMatch(a.shiftType, shiftType),
    );
    if (sameShiftConflict) {
      return {
        ok: false,
        message: `${personnelName} ${formatDateTR(date)} tarihinde zaten ${shiftNameTR(shiftType)} vardiyasına atanmıştır.`,
      };
    }

    const otherShiftConflict = this.assignmentCache().find(
      (a) =>
        a.personnelId === personnelId && a.date === date && !shiftsMatch(a.shiftType, shiftType),
    );
    if (otherShiftConflict) {
      return {
        ok: false,
        message: `${personnelName} ${formatDateTR(date)} tarihinde başka bir vardiyaya atanmıştır.`,
      };
    }

    const bookedMsg = deviceBookedMessageFor(
      this.assignmentCache(),
      deviceId,
      personnelId,
      date,
      shiftType,
      targetPersonnelType || src.personnelType,
    );
    if (bookedMsg) {
      return { ok: false, message: bookedMsg };
    }

    const s = this.normalizeShift(shiftType);
    if (s !== 'night') {
      const prev = new Date(date + 'T00:00:00');
      prev.setDate(prev.getDate() - 1);
      const prevStr = prev.toISOString().split('T')[0];
      const prevNight = this.assignmentCache().find(
        (a) =>
          a.personnelId === personnelId &&
          a.date === prevStr &&
          (this.normalizeShift(a.shiftType) === 'night' || (a.startTime && a.startTime >= '20')),
      );
      if (prevNight) {
        return {
          ok: false,
          message: `${personnelName}: önceki gece vardiyasının ertesinde ${shiftNameTR(shiftType)} atanamaz (dinlenme kuralı).`,
        };
      }
    }

    return { ok: true };
  }

  onDragOver(
    e: DragEvent | undefined,
    deviceId: string,
    date: string,
    shiftType: string,
    personnelType?: string | null,
  ): void {
    e?.preventDefault();
    const s = this.dragState();
    if (!s.isDragging || !s.sourceAssignment) return;
    const check = this.validateDropTarget(
      s.sourceAssignment,
      deviceId,
      date,
      shiftType,
      personnelType,
    );
    this.dragState.set({ ...s, targetSlot: { deviceId, date, shiftType }, isValid: check.ok });
  }

  onDragLeave(): void {
    this.dragState.update((s) => ({ ...s, targetSlot: null }));
  }

  onDrop(
    e: DragEvent | undefined,
    deviceId: string,
    date: string,
    shiftType: string,
    personnelType?: string | null,
    startTime?: string,
    endTime?: string,
  ): void {
    e?.preventDefault();
    const src = this.dragState().sourceAssignment;
    const scheduleId = this.currentSchedule()?.id;
    if (src && src.personnelId && scheduleId) {
      const check = this.validateDropTarget(src, deviceId, date, shiftType, personnelType);
      if (!check.ok) {
        this.notification.warning('Atama Engellendi', check.message || 'Bu atama yapılamaz.');
        this.dragState.set({
          isDragging: false,
          sourceAssignment: null,
          targetSlot: null,
          isValid: false,
        });
        return;
      }
      const times =
        startTime && endTime ? { startTime, endTime } : this.defaultSlotTimes(shiftType);
      this.scheduleApi
        .assignPersonnel(
          scheduleId,
          {
            deviceId,
            date,
            shiftType: this.normalizeShift(shiftType),
            personnelId: src.personnelId,
            personnelType: personnelType || undefined,
            ...times,
          },
          `Drag from ${src.deviceId}/${src.date}/${src.shiftType}`,
        )
        .pipe(takeUntil(this.destroy$))
        .subscribe({
          next: (updated) => {
            if (updated) {
              const vs = this.viewState();
              if (vs.status === 'success') this.viewState.set({ ...vs, schedule: updated });
            }
          },
          error: () => {
            /* toast servis katmanında gösterilir; mevcut görünüm korunur */
          },
        });
    }
    this.dragState.set({
      isDragging: false,
      sourceAssignment: null,
      targetSlot: null,
      isValid: false,
    });
  }

  onDragEnd(): void {
    this.dragState.set({
      isDragging: false,
      sourceAssignment: null,
      targetSlot: null,
      isValid: false,
    });
  }

