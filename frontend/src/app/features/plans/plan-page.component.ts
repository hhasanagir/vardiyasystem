  onDeleteAssignment(e: {
    deviceId: string;
    date: string;
    shiftType: string;
    personnelType?: string | null;
    personnelId?: string;
  }): void {
    const scheduleId = this.currentSchedule()?.id;
    if (!scheduleId || !e.personnelId) return;
    const assignment = this.assignmentCache().find(
      (a) =>
        a.deviceId === e.deviceId &&
        a.date === e.date &&
        a.personnelId === e.personnelId &&
        (a.shiftType === this.normalizeShift(e.shiftType) ||
          a.shiftType.includes(e.shiftType.toLowerCase())),
    );
    if (!assignment || !assignment.id) return;
    this.scheduleApi
      .removeAssignment(scheduleId, assignment.id, 'Manuel silme')
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (updated) => {
          if (updated) {
            const vs = this.viewState();
            if (vs.status === 'success') this.viewState.set({ ...vs, schedule: updated });
            this.notification.success('Atama Kaldırıldı', 'Vardiya ataması başarıyla kaldırıldı.');
          }
        },
        error: () => this.notification.error('Hata', 'Atama kaldırılamadı.'),
      });
  }

